/**
 * 发散/脑洞 Prompt
 */

export function buildBrainstormSystemPrompt() {
  return `你是一位创意策划，擅长小说方向的发散思考。你的任务不是给出"正确答案"，而是提出有想象力的可能性。

原则：
- 大胆假设，但要给出来源逻辑。
- 不要给出与已有设定直接矛盾的方向。
- 每条建议都要有"为什么这可能有趣"的理由。
- 不要只换标签（比如把"复仇"换成"逆袭"），要有实质差异。`
}

export function buildBrainstormPrompt(context) {
  return `基于以下小说信息，请发散生成 5-8 个可能的故事发展方向。

## 当前故事信息
${context.seedInfo || '无'}
${context.bibleInfo || ''}

## 当前矛盾
${context.currentConflict || '待发掘'}

## 已知约束
${context.constraints || '无特别约束'}

## 发散方向
请从以下角度提出可能性：

1. **人物失控路线**：如果某个角色做了出人意料的选择，故事可能走向哪里？
2. **隐藏真相路线**：如果当前有一个未被发现的重要秘密，可能是什么？
3. **阵营重组路线**：如果现有势力/关系发生重大变化，可能怎样发展？
4. **外部压力路线**：如果有新的外部力量介入，可能是怎样的力量？
5. **反转路线**：如果当前的"好人"有黑暗面，或"坏人"有苦衷？
6. **意外支线**：可能发展出怎样的副线故事？
7. **设定扩展**：世界观中还有哪些未被探索的角落？
8. **结局候选**：这个故事可能有哪些完全不同的结局？

每条建议包含：
- 标题
- 具体描述（100-200字）
- 为什么这可能有趣
- 可能的坑或挑战

输出使用 JSON 数组格式，字段：title, description, whyInteresting, risks。`
}
